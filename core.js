// ------------------------------------------------- положение относительно норм
// Переводит балл в 0…1 так, что каждый из пяти уровней занимает пятую часть:
// 0.4–0.6 это средний уровень. Нужен для отпечатка, радара и карты.
export function norm01(key, sc) {
  const t = [0, ...NORMS[key], maxOf(key)];
  for (let j = 0; j < 5; j++) {
    if (sc < t[j + 1]) return Math.min(1, (j + (sc - t[j]) / (t[j + 1] - t[j])) / 5);
  }
  return 1;
}

/** Промежуточная оценка по уже данным ответам (null пропускается). */
export function partial(answers) {
  const out = {};
  for (const [k, s] of Object.entries(SUB)) {
    let sum = 0, n = 0;
    for (const q of s.direct) if (answers[q - 1] != null) { sum += answers[q - 1]; n++; }
    for (const q of s.reverse) if (answers[q - 1] != null) { sum += MAX_ITEM - answers[q - 1]; n++; }
    out[k] = n ? norm01(k, Math.round(sum / n * itemsOf(k))) : 0.5;
  }
  return out;
}

