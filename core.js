export function typeOf(r) {
  const vx = norm01('VEI', r.VEI.score), vy = norm01('MEI', r.MEI.score);
  const mid = (v) => v >= 0.4 && v < 0.6;
  if (mid(vx) && mid(vy)) return 'balance';
  const x = vx >= 0.5, y = vy >= 0.5;
  return x && y ? 'conductor' : y ? 'empath' : x ? 'autonomous' : 'autopilot';
}
