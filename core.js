export const LEVELS = ['очень низкий', 'низкий', 'средний', 'высокий', 'очень высокий'];

const MAX_ITEM = 3;
const itemsOf = (k) => SUB[k].direct.length + SUB[k].reverse.length;
const maxOf = (k) => (SUB[k] ? itemsOf(k) : SCALES[k].parts.reduce((s, p) => s + itemsOf(p), 0)) * MAX_ITEM;

export function levelOf(key, score) {
  return NORMS[key].filter((t) => score >= t).length;   // 0…4
}

/** Ответы: массив из 46 чисел 0…3, где 0 «совсем не так», 3 «совершенно так». */
export function validAnswers(a) {
  return Array.isArray(a) && a.length === QUESTIONS.length &&
    a.every((v) => Number.isInteger(v) && v >= 0 && v <= MAX_ITEM);
}

export function score(answers) {
  if (!validAnswers(answers)) throw new Error('нужно 46 ответов от 0 до 3');
  const raw = {};
  for (const [k, s] of Object.entries(SUB)) {
    raw[k] = s.direct.reduce((t, n) => t + answers[n - 1], 0) +
             s.reverse.reduce((t, n) => t + (MAX_ITEM - answers[n - 1]), 0);
  }
  for (const [k, s] of Object.entries(SCALES)) raw[k] = s.parts.reduce((t, p) => t + raw[p], 0);

  const out = {};
  for (const k of Object.keys(raw)) out[k] = { score: raw[k], max: maxOf(k), level: levelOf(k, raw[k]) };

  // Сильная сторона и точка роста среди пяти субшкал: сначала по уровню
  // нормы, при равенстве по доле от максимума.
  const rank = Object.keys(SUB).sort((a, b) =>
    (out[a].level - out[b].level) || (out[a].score / out[a].max - out[b].score / out[b].max));
  out.weak = rank[0];
  out.strong = rank[rank.length - 1];
  return out;
}

